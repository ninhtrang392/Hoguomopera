import {readFileSync,writeFileSync} from 'node:fs';
import vm from 'node:vm';

// Browser entrypoints are classic deferred scripts so file:// previews do not
// depend on cross-origin module imports. Source modules remain independently tested.
const read=name=>readFileSync(`dist/${name}`,'utf8');
const source=name=>read(name).replace(/^import\s+.*?;\s*$/gm,'').replace(/^export /gm,'');
const catalogue=read('programme-data.js');
for(const [entry,output,extra] of [
  ['booking.js','booking.bundle.js',`const bundledSeatReference = ${read('seat-layout.json')};\n${read('vendor/qrcode.js').replace('export {qrcode};','')}\n${source('seat-map.js')}\n${source('booking-demo.js')}`],
  ['programme.js','programme.bundle.js','']
]){
  const code=`/* Generated by node scripts/build-booking.mjs. Edit source modules. */\n(() => {\ntry {\n${catalogue}\n${source('booking-api.js')}\n${extra}\n${source(entry)}\n} catch (error) {\nconsole.error('Booking initialization failed:', error);\nconst notice = document.querySelector('#booking-notice, #programme-status');\nif (notice) { notice.hidden = false; notice.textContent = 'Không thể tải giao diện đặt vé. Vui lòng tải lại trang hoặc mở qua máy chủ local.'; }\n}\n})();\n`;
  new vm.Script(code,{filename:output});
  writeFileSync(`dist/${output}`,code);
  console.log(`Built ${output}`);
}
